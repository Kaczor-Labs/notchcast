/// #909: every add-on command draws its own symbol in the launcher, never upstream's question mark.
@main
@MainActor
enum NotchcastCommandIconTests {
    static let addons: [any NotchcastAddon.Type] = [
        SmallCommandsAddon.self, DownloadsAddon.self, ScreenshotsAddon.self, PastePlainTextAddon.self,
    ]

    static var failures = 0
    static var checks = 0

    static func check(_ name: String, _ value: Bool) {
        checks += 1
        if !value { failures += 1; print("FAIL \(name)") }
    }

    static func main() {
        everyCommandingAddonIsWalked()
        let domain = "tinycast.notchcast-command-icons-test.\(UUID())"
        let defaults = UserDefaults(suiteName: domain)!
        defer { defaults.removePersistentDomain(forName: domain) }
        let index = AppIndex(
            ranking: LauncherRankingStore(
                fileURL: FileManager.default.temporaryDirectory.appendingPathComponent("\(domain).json")),
            aliases: AliasStore(defaults: defaults))
        let switches = Dictionary(addons.flatMap { $0.switches }.map { ($0.id, $0) }, uniquingKeysWith: { a, _ in a })
        let commands = addons.flatMap { $0.commands }
        // Built exactly as NotchcastCore's onCommandsChanged builds them.
        index.extraCommandEntries = commands.map {
            AppEntry(notchcastCommand: $0.id, name: $0.name, symbol: $0.symbol, keywords: $0.keywords,
                     owner: .notchcast(switches[$0.switchID].map { NotchcastPane.holding($0.category) } ?? .island))
        }
        check("the add-ons declare commands to walk", commands.count >= 10)
        for command in commands {
            guard let entry = index.apps.first(where: { $0.id == command.id }) else {
                check("\(command.id) reaches the launcher index", false)
                continue
            }
            let icon = entry.iconSource
            check("\(command.id) does not draw the question mark (\(icon))", icon != .symbol("questionmark"))
            guard case .tile(let symbol, _) = icon else {
                check("\(command.id) draws a tile like stock commands (\(icon))", false)
                continue
            }
            check("\(command.id) draws its own symbol \(command.symbol), got \(symbol)", symbol == command.symbol)
            check("\(command.id)'s symbol \(symbol) is a real SF Symbol",
                  NSImage(systemSymbolName: symbol, accessibilityDescription: nil) != nil)
        }
        print("\(checks) add-on command icon checks; \(failures) failures")
        if failures > 0 { exit(1) }
        print("PASSED")
    }

    /// A new add-on with commands fails here until this harness compiles it too.
    static func everyCommandingAddonIsWalked() {
        let root = URL(fileURLWithPath: FileManager.default.currentDirectoryPath)
            .appendingPathComponent("Tinycast/Features/Notchcast")
        let folders = (try? FileManager.default.contentsOfDirectory(atPath: root.path)) ?? []
        let walked = Set(addons.map { String(describing: $0) })
        var declaring: [String] = []
        for folder in folders {
            let file = root.appendingPathComponent("\(folder)/\(folder)Addon.swift")
            guard let text = try? String(contentsOf: file, encoding: .utf8),
                  text.contains("static let commands") else { continue }
            declaring.append("\(folder)Addon")
        }
        check("an add-on folder declares commands", !declaring.isEmpty)
        for addon in declaring {
            check("\(addon) declares commands, so this harness walks it", walked.contains(addon))
        }
    }
}

