import AppKit

@main
@MainActor
struct DownloadsDistillQueueTest {
    static func main() async throws {
        let root = FileManager.default.temporaryDirectory.appending(path: "nc-downloads-distill-queue-\(UUID())")
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: root) }
        let suite = "nc-downloads-distill-queue.\(UUID())"
        let defaults = UserDefaults(suiteName: suite)!
        defer { defaults.removePersistentDomain(forName: suite) }
        let preferences = NotchcastPreferences(defaults: defaults, switches: DownloadsAddon.switches)
        let hub = NotchcastTapHub(syntheticTag: 0, isTrusted: { false }) { _ in
            preconditionFailure("the harness never installs a tap")
        }
        let context = NotchcastContext(
            defaults: defaults, preferences: preferences, presenter: NoticeLog(), hub: hub,
            transcription: NotchcastTranscriptionRunner(dictation: FakeDictation()), now: { .now }, onTapsChanged: {})
        var clipboard = ""
        let module = DownloadsModule(context: context, environment: .init(
            downloads: root.appending(path: "Downloads"), queues: root.appending(path: "queues"),
            tools: DownloadToolLookup(directories: [], home: root), clipboard: { clipboard }))
        context.attach(module)
        module.start()
        defer { module.stop() }
        precondition(module.distillRows == nil)
        preferences.set("distill", on: true)
        try await eventually { module.distillRows == [] }
        let queue = module.distill.queue!
        let probe = Probe()
        queue.register(Runner(probe: probe))

        let names = (0..<25).map { "example.com/\($0)" }
        clipboard = names.map { "https://www.\($0)" }.joined(separator: "\n")
        let addLinks = DownloadsAddon.commands.first { $0.slug == "add-links-to-distill" }!
        addLinks.run(context)
        let held = module.distillRows!
        precondition(held.map(\.name) == names && held.allSatisfy { $0.state == .held })
        precondition(held[0].note == "Held until Run Distill")
        precondition(DistillQueueList.countLine(held) == "25 links queued")
        let coded = try JSONEncoder().encode(held)
        let decoded = try JSONDecoder().decode([DistillQueueList.Row].self, from: coded)
        precondition(decoded == held)
        let dropped = queue.enqueue(kind: DistillRunner.kind, sources: ["/tmp/dropped.pdf"], held: true)[0]
        precondition(module.distillRows == held, "dropped files stay outside the list")
        queue.remove(dropped.id)

        module.perform(.remove(held[0].id))
        module.perform(.run)
        try await eventually { module.distillRows?.first?.note == "Working…" }
        precondition(module.distillRows?.prefix(2).map(\.state) == [.running, .waiting])
        module.perform(.remove(held[2].id))
        module.perform(.remove(held[1].id))
        try await eventually { probe.started == [names[1], names[3]] }
        precondition(probe.cancelled == [names[1]])
        precondition(module.distillRows?.first?.id == held[3].id)
        precondition(module.distillRows?.contains { held.prefix(3).map(\.id).contains($0.id) } == false)

        probe.released.formUnion(names.dropFirst(3))
        try await eventually { module.distillRows?.allSatisfy { $0.state.isFinished } == true }
        let finished = module.distillRows!
        precondition(finished.map(\.name) == Array(names.dropFirst(3).reversed()))
        let failed = finished.first { $0.state == .failed }!
        precondition(failed.name == names[4] && failed.note == "Failed: Fixture failure" && failed.canRetry)
        precondition(finished.first?.note == "Saved Page.md")
        precondition(DistillQueueList.countLine(finished) == "0 links queued · 1 failed")

        clipboard = "https://example.com/later"
        addLinks.run(context)
        precondition(module.distillRows?.first?.name == "example.com/later")
        probe.released.remove(names[4])
        let beforeRetry = probe.started
        module.perform(.retry(failed.id))
        try await eventually { probe.started == beforeRetry + [names[4]] }
        precondition(module.distillRows?.prefix(2).map(\.state) == [.held, .running])
        precondition(queue.jobs.first { $0.id == failed.id }?.detail == nil)
        probe.released.insert(names[4])
        try await eventually { module.distillRows?.first { $0.id == failed.id }?.state == .done }
        precondition(module.distillRows?.dropFirst(2).map(\.id) == finished.filter { $0.id != failed.id }.map(\.id))
        precondition(probe.started == beforeRetry + [names[4]], "retry starts only that link")

        let later = module.distillRows!.first!
        queue.cancel(later.id)
        addLinks.run(context)
        let replacement = module.distillRows!.first!
        module.perform(.retry(later.id))
        precondition(module.distillRows?.first == replacement && replacement.state == .held)
        precondition(module.distillRows?.contains { $0.id == later.id } == false)

        let file = queue.enqueue(kind: DistillRunner.kind, sources: [dropped.source], held: true)[0]
        module.perform(.remove(file.id))
        precondition(queue.jobs.contains { $0.id == file.id }, "a Settings action cannot remove a file")
        await queue.stop()
        print("Distill queue: 25 links, ordered live states, removal, failure and isolated retry")
    }

    private static func eventually(_ condition: () -> Bool) async throws {
        let deadline = ContinuousClock.now.advanced(by: .seconds(8))
        while !condition() {
            guard ContinuousClock.now < deadline else { throw CocoaError(.coderReadCorrupt) }
            try await Task.sleep(for: .milliseconds(5))
        }
    }

    @MainActor
    private final class Probe {
        var started: [String] = []
        var cancelled: [String] = []
        var released: Set<String> = []
    }

    private struct Runner: DownloadRunner {
        let kind = DistillRunner.kind
        let tools: [DownloadTool] = []
        let probe: Probe

        @MainActor
        func run(_ job: DownloadJob, context: DownloadRunContext) async throws -> URL? {
            let name = DistillQueueList.rows([job])[0].name
            let firstRun = !probe.started.contains(name)
            context.report(.init(stage: "Working…"))
            probe.started.append(name)
            do {
                while !probe.released.contains(name) { try await Task.sleep(for: .milliseconds(5)) }
                try Task.checkCancellation()
            } catch {
                probe.cancelled.append(name)
                throw error
            }
            if name == "example.com/4", firstRun { throw DistillFailure.failed("Fixture failure") }
            return context.destination.appending(path: "Page.md")
        }
    }
}

@MainActor
private final class NoticeLog: IslandPresenting {
    var notices: [IslandNotice] = []

    func showLevel(_ level: IslandLevel) {}
    func post(_ notice: IslandNotice, onTap: (@MainActor () -> Void)?) { notices.append(notice) }
    func end(notice id: String) {}
    func setStatus(_ status: IslandStatus?, for id: String, onTap: (@MainActor () -> Void)?) {}
    func setMenuRows(_ rows: [IslandMenuRow], owner: String, onSelect: @escaping @MainActor (String) -> Void) {}
}

