    /// Inert: the harness never touches the Mac's real default apps.
    static func live() -> Self {
        Self(own: "", holder: { _ in .init(current: nil, candidates: []) }, setDefault: { _, _ in nil },
             hasAria2c: { false }, name: { _ in nil })
    }
}
