/// Distill through core's transcribe: text written, timestamps on and off, busy ends the run, cancel stops.
@main
@MainActor
struct DownloadsDistillTest {
    static func main() async throws {
        model()
        let root = FileManager.default.temporaryDirectory.appending(path: "nc-downloads-distill-\(UUID().uuidString)")
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: root) }
        try await distill(root)
        try await isolation(root)
        print("Downloads distill: transcript written, timestamps on/off, stop and restart drop a run, "
              + "busy ends the run, cancel stops, each queue stops only its own tools")
    }

    private static func model() {
        let segments = [DistillTranscript.Segment(start: 0, text: " one "), .init(start: 240, text: ""),
                        .init(start: 3_725, text: "two")]
        expect(DistillTranscript.text(segments, times: false) == "one\ntwo\n", "plain text skips empty chunks")
        expect(DistillTranscript.text(segments, times: true) == "[00:00:00] one\n[01:02:05] two\n",
               "timestamps lead each line")
        expect(DistillTranscript.text([], times: true).isEmpty, "no speech is no text")
        expect(DistillTranscript.stem(channel: "Chan/nel", title: "Talk: One") == "Chan-nel - Talk - One",
               "a name is one safe path component")
        expect(DistillTranscript.stem(channel: nil, title: "..") == "Untitled", "a name never walks up")
        expect(YtDlpAudio.isMedia(URL(string: "https://www.youtube.com/watch?v=abc")!)
               && !YtDlpAudio.isMedia(URL(string: "https://example.com/post")!), "media hosts transcribe, pages save")
    }

    private static func distill(_ root: URL) async throws {
        let bin = root.appending(path: "bin", directoryHint: .isDirectory)
        try FileManager.default.createDirectory(at: bin, withIntermediateDirectories: true)
        try tool(bin, "yt-dlp", """
            for a in "$@"; do [ "$a" = --skip-download ] && { echo '{"id":"v","title":"Talk: One","channel":"Chan"}'; exit 0; }; done
            prev=; for a in "$@"; do [ "$prev" = -o ] && out="${a%.*}.m4a"; prev=$a; done
            printf audio > "$out"
            """)
        try tool(bin, "ffmpeg", """
            for a in "$@"; do last=$a; done
            for i in 0 1 2; do printf wav > "$(printf "$last" "$i")"; done
            """)
        let suite = "nc-downloads-distill-test.\(UUID().uuidString)"
        let defaults = UserDefaults(suiteName: suite)!
        defer { defaults.removePersistentDomain(forName: suite) }
        let downloads = root.appending(path: "home/Downloads", directoryHint: .isDirectory)
        let work = root.appending(path: "work", directoryHint: .isDirectory)
        var clipboard = ""
        let environment = DownloadsModule.Environment(
            downloads: downloads, queues: root.appending(path: "queues", directoryHint: .isDirectory),
            tools: DownloadToolLookup(directories: [bin], home: root),
            clipboard: { clipboard }, work: work)
        let hub = NotchcastTapHub(syntheticTag: 0, isTrusted: { false }) { _ in
            preconditionFailure("the harness never installs a tap")
        }
        let preferences = NotchcastPreferences(defaults: defaults, switches: DownloadsAddon.switches)
        let presenter = NoticeLog()
        let dictation = FakeDictation()
        dictation.result = .success("hello")
        let context = NotchcastContext(defaults: defaults, preferences: preferences, presenter: presenter, hub: hub,
                                       transcription: NotchcastTranscriptionRunner(dictation: dictation),
                                       now: { .now }, onTapsChanged: {})
        let module = DownloadsModule(context: context, environment: environment)
        context.attach(module)
        func command(_ slug: String) { DownloadsAddon.commands.first { $0.slug == slug }!.run(context) }
        func jobs() -> [DownloadJob] { module.distill.queue?.jobs ?? [] }
        func distilled(_ link: String) async throws -> DownloadJob {
            clipboard = link
            command("add-links-to-distill")
            command("run-distill")
            try await eventually { jobs().last.map { $0.source == link && $0.state.isFinished } ?? false }
            return jobs().last!
        }

        module.start()
        preferences.set("distill", on: true)
        try await eventually { module.distill.queue != nil }
        expect(module.distill.destination == downloads.appending(path: "Distill/Raw", directoryHint: .isDirectory),
               "Distill lands in ~/Downloads/Distill/Raw")

        let plain = try await distilled("https://www.youtube.com/watch?v=one")
        expect(plain.state == .done, "a media link is distilled: \(plain.detail ?? "")")
        let plainFile = URL(filePath: plain.output!)
        expect(plainFile.lastPathComponent == "Chan - Talk - One.txt", "named after channel and title")
        try expect(String(contentsOf: plainFile, encoding: .utf8) == "hello\nhello\nhello\n",
               "timestamps off: one plain line per chunk")
        expect(dictation.calls.count == 3, "every chunk goes through core's transcribe, in order")

        preferences.set("distillTimestamps", on: true)
        let timed = try await distilled("https://www.youtube.com/watch?v=two")
        try expect(String(contentsOf: URL(filePath: timed.output!), encoding: .utf8)
               == "[00:00:00] hello\n[00:04:00] hello\n[00:08:00] hello\n", "timestamps on: each chunk's start")

        let raw = module.distill.destination
        let before = Set(try FileManager.default.contentsOfDirectory(atPath: raw.path))
        func transcripts() -> Set<String> {
            Set((try? FileManager.default.contentsOfDirectory(atPath: raw.path)) ?? [])
        }
        func workEmpty() -> Bool { (try? FileManager.default.contentsOfDirectory(atPath: work.path).isEmpty) ?? true }
        func quiet(since mark: Int) -> Bool {
            !presenter.notices.dropFirst(mark).contains {
                $0.isFailure || $0.id == "distill.progress.saved" || $0.id == "distill.progress.cancelled"
            }
        }
        func suspended(_ link: String) async throws -> DownloadJob {
            let started = dictation.calls.count
            dictation.holds = true
            clipboard = link
            command("add-links-to-distill")
            command("run-distill")
            try await eventually { dictation.calls.count == started + 1 }
            return jobs().first { $0.source == link }!
        }

        dictation.finishesDespiteCancel = true
        let late = try await suspended("https://www.youtube.com/watch?v=late")
        let lateCalls = dictation.calls.count
        var mark = presenter.notices.count
        module.stop()
        module.start()
        dictation.holds = false
        dictation.release()
        try await eventually { module.distill.queue != nil }
        dictation.finishesDespiteCancel = false
        let restarted = jobs().first { $0.id == late.id }
        expect(restarted != nil && restarted?.state != .done && restarted?.output == nil,
               "a reply that lands after restart is not applied to its job")
        expect(transcripts() == before, "a reply that lands after restart writes no transcript")
        expect(dictation.calls.count == lateCalls && workEmpty() && quiet(since: mark),
               "a late reply transcribes no further chunk, leaves no scratch audio and posts nothing")

        let stopped = try await suspended("https://www.youtube.com/watch?v=stop")
        mark = presenter.notices.count
        module.stop()
        dictation.holds = false
        dictation.release()
        module.start()
        try await eventually { module.distill.queue != nil }
        expect(jobs().first { $0.id == stopped.id }?.state == .interrupted,
               "stop mid-transcription applies no result: the run stays interrupted")
        expect(workEmpty(), "stop mid-transcription removes the scratch audio")
        expect(quiet(since: mark) && transcripts() == before, "stop mid-transcription posts and writes nothing")

        dictation.isDictating = true
        let calls = dictation.calls.count
        clipboard = "https://www.youtube.com/watch?v=busy https://www.youtube.com/watch?v=later"
        command("add-links-to-distill")
        command("run-distill")
        try await eventually { jobs().contains { $0.source.hasSuffix("busy") && $0.state.isFinished } }
        try await Task.sleep(for: .milliseconds(100))
        let busy = jobs().first { $0.source.hasSuffix("busy") }!
        expect(busy.state == .failed, "busy fails the link at once, never waits")
        let notice = presenter.notices.first { $0.id == "distill.progress.failed." + busy.id }
        expect(notice?.isFailure == true && notice?.seconds == nil, "busy is a failure notice without seconds")
        expect(notice?.text.hasSuffix("Dictation is in use. Run Distill again when it is free.") == true,
               "the notice says why")
        expect(jobs().first { $0.source.hasSuffix("later") }?.state == .held, "busy ends the run: the rest waits")
        expect(dictation.calls.count == calls, "busy reaches no dictation")
        dictation.isDictating = false

        dictation.holds = true
        command("run-distill")
        try await eventually { dictation.calls.count == calls + 1 }
        let later = jobs().first { $0.source.hasSuffix("later") }!
        module.distill.queue!.cancel(later.id)
        dictation.holds = false
        dictation.release()
        try await eventually { (try? FileManager.default.contentsOfDirectory(atPath: work.path).isEmpty) ?? true }
        try await Task.sleep(for: .milliseconds(200))
        expect(dictation.calls.count == calls + 1, "cancel mid-chunk: no further chunk is transcribed")
        let cancelled = jobs().first { $0.id == later.id }
        expect(cancelled?.state == .cancelled && cancelled?.output == nil, "a cancelled link writes no transcript")
        module.stop()
    }

    /// Stopping either queue while the other runs a tool leaves that tool's process alive.
    private static func isolation(_ root: URL) async throws {
        let folder = root.appending(path: "isolation", directoryHint: .isDirectory)
        let bin = folder.appending(path: "bin", directoryHint: .isDirectory)
        let pids = folder.appending(path: "pids", directoryHint: .isDirectory)
        for directory in [bin, pids] {
            try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        }
        try tool(bin, "yt-dlp", """
            case "$*" in *v=video*) echo $$ > '\(pids.path)/video';; *) echo $$ > '\(pids.path)/distill';; esac
            exec /bin/sleep 30
            """)
        try tool(bin, "ffmpeg", "exit 0")
        let suite = "nc-downloads-isolation-test.\(UUID().uuidString)"
        let defaults = UserDefaults(suiteName: suite)!
        defer { defaults.removePersistentDomain(forName: suite) }
        var clipboard = ""
        let environment = DownloadsModule.Environment(
            downloads: folder.appending(path: "Downloads", directoryHint: .isDirectory),
            queues: folder.appending(path: "queues", directoryHint: .isDirectory),
            tools: DownloadToolLookup(directories: [bin], home: root),
            clipboard: { clipboard },
            work: folder.appending(path: "work", directoryHint: .isDirectory))
        let hub = NotchcastTapHub(syntheticTag: 0, isTrusted: { false }) { _ in
            preconditionFailure("the harness never installs a tap")
        }
        let preferences = NotchcastPreferences(defaults: defaults, switches: DownloadsAddon.switches)
        let context = NotchcastContext(defaults: defaults, preferences: preferences, presenter: NoticeLog(), hub: hub,
                                       transcription: NotchcastTranscriptionRunner(dictation: FakeDictation()),
                                       now: { .now }, onTapsChanged: {})
        let module = DownloadsModule(context: context, environment: environment)
        context.attach(module)
        func command(_ slug: String) { DownloadsAddon.commands.first { $0.slug == slug }!.run(context) }
        func pid(_ name: String) -> pid_t? {
            (try? String(contentsOf: pids.appending(path: name), encoding: .utf8))
                .flatMap { pid_t($0.trimmingCharacters(in: .whitespacesAndNewlines)) }
        }
        func alive(_ pid: pid_t) -> Bool { kill(pid, 0) == 0 }

        module.start()
        preferences.set("downloads", on: true)
        preferences.set("distill", on: true)
        try await eventually { module.downloads.queue != nil && module.distill.queue != nil }
        clipboard = "https://www.youtube.com/watch?v=video"
        command("download-video")
        try await eventually { pid("video") != nil }
        let video = pid("video")!
        preferences.set("distill", on: false)
        try await eventually { module.distill.queue == nil }
        try await Task.sleep(for: .milliseconds(400))
        expect(alive(video) && module.downloads.queue?.jobs.first?.state == .running,
               "stopping an idle Distill leaves a running download's process alive")

        preferences.set("distill", on: true)
        try await eventually { module.distill.queue != nil }
        clipboard = "https://www.youtube.com/watch?v=distill"
        command("add-links-to-distill")
        command("run-distill")
        try await eventually { pid("distill") != nil }
        let distill = pid("distill")!
        preferences.set("downloads", on: false)
        try await eventually { module.downloads.queue == nil }
        try await eventually { !alive(video) }
        try await Task.sleep(for: .milliseconds(400))
        expect(alive(distill) && module.distill.queue?.jobs.first?.state == .running,
               "stopping Downloads ends its own process and leaves a running Distill's alive")
        module.stop()
        try await eventually { !alive(distill) }
    }

    private static func tool(_ bin: URL, _ name: String, _ script: String) throws {
        let file = bin.appending(path: name)
        try Data("#!/bin/sh\n\(script)\n".utf8).write(to: file)
        try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: file.path)
    }

    private static func expect(_ value: @autoclosure () throws -> Bool, _ message: String) rethrows {
        let held = try value()
        precondition(held, message)
    }

    private static func eventually(_ condition: () -> Bool) async throws {
        let deadline = ContinuousClock.now.advanced(by: .seconds(10))
        while !condition() {
            guard ContinuousClock.now < deadline else { throw HarnessError.timeout }
            try await Task.sleep(for: .milliseconds(5))
        }
    }

    private enum HarnessError: Error { case timeout }
}

@MainActor
