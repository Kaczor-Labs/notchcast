#!/usr/bin/env python3
"""notchcast/addons.py on scratch trees: registry order, README tab lines, refusals; and the real tree generates."""
from pathlib import Path
import importlib.util
import subprocess
import sys
import tempfile
import unittest

sys.dont_write_bytecode = True
SCRIPT = Path(__file__).resolve().parent / 'addons.py'
NC = 'Tinycast/Features/Notchcast/'
README = ('# App\n- **Settings**\n  <!-- addon-tabs:start -->\n  - **Island**: look, outline.\n  - **Capture**:\n'
          '  - **Power**:\n  <!-- addon-tabs:end -->\nEnd\n')


def write(root, path, text):
    target = root / path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text)


class AddonsTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        write(self.root, 'notchcast/README.public.md', README)
        write(self.root, NC + 'Core/Service/NotchcastAddon.swift', 'protocol NotchcastAddon {}\n')
        self.addon('Shots', 20, '// notchcast-readme: Capture: screenshots\n// notchcast-readme: Island: a page\n')
        self.addon('Alpha', 10)
        self.addon('Beta', 20)

    def tearDown(self):
        self.tmp.cleanup()

    def addon(self, folder, order, extra=''):
        write(self.root, f'{NC}{folder}/{folder}Addon.swift',
              f'// notchcast-addon-order: {order}\n{extra}import Foundation\n\nenum {folder}Addon: NotchcastAddon {{}}\n')

    def run_script(self, command):
        return subprocess.run([sys.executable, str(SCRIPT), command, '--root', str(self.root)],
                              capture_output=True, text=True)

    def test_registry_follows_the_order_lines_and_ties_go_by_type_name(self):
        self.assertEqual(self.run_script('registry').returncode, 0)
        registry = (self.root / NC / 'NotchcastRegistry.swift').read_text()
        self.assertIn('    static let addons: [any NotchcastAddon.Type] = [\n        AlphaAddon.self,\n'
                      '        BetaAddon.self,\n        ShotsAddon.self,\n    ]\n', registry)
        self.assertTrue(registry.startswith('// Generated by notchcast/addons.py'))
        self.assertFalse((self.root / 'README.md').exists(), 'registry alone never writes the README')
        self.assertEqual(self.run_script('next').stdout, '30\n')

    def test_readme_appends_each_phrase_to_its_tab_and_drops_empty_tabs(self):
        self.assertEqual(self.run_script('generate').returncode, 0)
        self.assertEqual((self.root / 'README.md').read_text(),
                         '# App\n- **Settings**\n  <!-- addon-tabs:start -->\n  - **Island**: look, outline, a page.\n'
                         '  - **Capture**: screenshots.\n  <!-- addon-tabs:end -->\nEnd\n')

    def test_a_missing_order_or_unknown_tab_is_refused(self):
        write(self.root, f'{NC}Gamma/GammaAddon.swift', 'enum GammaAddon: NotchcastAddon {}\n')
        result = self.run_script('registry')
        self.assertEqual(result.returncode, 1)
        self.assertIn('Gamma/GammaAddon.swift: declares 1 add-on types and 0 order lines', result.stderr)
        self.addon('Gamma', 5, '// notchcast-readme: Nowhere: a thing\n')
        result = self.run_script('generate')
        self.assertEqual(result.returncode, 1)
        self.assertIn('Gamma: no tab line **Nowhere** in README.public.md', result.stderr)

    def test_the_real_tree_generates_and_its_registry_is_what_it_generates(self):
        root = SCRIPT.parent.parent
        committed = (root / NC / 'NotchcastRegistry.swift').read_text()
        spec = importlib.util.spec_from_file_location('addons', SCRIPT)
        addons = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(addons)
        generated = addons.registry_text(addons.declarations(root))
        # A branch adding an add-on carries main's registry until main regenerates it, so only main's lines are pinned.
        lines = [line for line in committed.splitlines() if line.endswith('.self,')]
        self.assertEqual(lines, [line for line in generated.splitlines() if line in lines])
        addons.readme_text((root / 'notchcast/README.public.md').read_text(), addons.declarations(root))


if __name__ == '__main__':
    unittest.main()
