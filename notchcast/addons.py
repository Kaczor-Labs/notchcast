#!/usr/bin/env python3
"""The add-on lists, generated from each add-on's own file (notchcast/docs/addons.md §1), so no two add-on PRs edit one line.

Each `<Folder>Addon.swift` declares itself at column 0:
  // notchcast-addon-order: <n>              its place in NotchcastRegistry.addons (ties go by type name)
  // notchcast-readme: <Tab>: <phrase>        optional, repeatable: a phrase on that tab's line in the README,
                                             joined by ', ', or by a space after one ending in ',' or ';'

Usage:
  addons.py registry [--root R]   write NotchcastRegistry.swift and check the README lines (project.yml's preGenCommand)
  addons.py generate [--root R]   write the registry and README.md (ci.py regenerate, on main only)
  addons.py next [--root R]       print the order a new add-on takes: the highest one plus 10
Exit 1 when an add-on's declaration is missing or malformed.
"""
import argparse
import pathlib
import re
import sys

ROOT_DIR = 'Tinycast/Features/Notchcast/'
REGISTRY = ROOT_DIR + 'NotchcastRegistry.swift'
CORE_DIRS = {'Core', 'Hidden'}
ADDON_DECL = re.compile(r'\b(?:struct|enum|class)\s+(\w+)\b[^{]*\bNotchcastAddon\b')
ORDER = re.compile(r'^// notchcast-addon-order: *(\S*)$', re.M)
README = re.compile(r'^// notchcast-readme: *(.*)$', re.M)
TABS_START, TABS_END = '<!-- addon-tabs:start -->', '<!-- addon-tabs:end -->'
TAB_LINE = re.compile(r'^  - \*\*(.+?)\*\*:(.*)$')


class Declaration(Exception):
    pass


def declarations(root):
    """[(order, type, folder, [(tab, phrase)])] for every add-on type, sorted into registry order."""
    found, problems = [], []
    base = pathlib.Path(root) / ROOT_DIR
    folders = sorted(p for p in base.iterdir() if p.is_dir() and p.name not in CORE_DIRS) if base.is_dir() else []
    for folder in folders:
        for path in sorted(folder.rglob('*.swift')):
            text = path.read_text()
            types, orders, readmes = ADDON_DECL.findall(text), ORDER.findall(text), README.findall(text)
            where = path.relative_to(root)
            if not types and not orders and not readmes:
                continue
            if len(types) != 1 or len(orders) != 1 or not orders[0].isdigit():
                problems.append(f'{where}: declares {len(types)} add-on types and {len(orders)} order lines; '
                                f'the file of a `: NotchcastAddon` type holds it and one `// notchcast-addon-order: <n>`')
                continue
            if any(': ' not in line for line in readmes):
                problems.append(f'{where}: a README line reads `// notchcast-readme: <Tab>: <phrase>`')
                continue
            found.append((int(orders[0]), types[0], folder.name, [tuple(line.split(': ', 1)) for line in readmes]))
    if problems:
        raise Declaration('\n'.join(problems))
    return sorted(found, key=lambda d: (d[0], d[1]))


def registry_text(decls):
    lines = ''.join(f'        {d[1]}.self,\n' for d in decls)
    return ('// Generated by notchcast/addons.py from each add-on\'s `// notchcast-addon-order:` line; never edit it.\n'
            '@MainActor\nenum NotchcastRegistry {\n    static let addons: [any NotchcastAddon.Type] = [\n'
            f'{lines}    ]\n}}\n')


def joined(parts):
    """Phrases joined by ', '; one that ends in ',' or ';' brings its own punctuation and takes a space."""
    text = ''
    for part in parts:
        text += part if not text else (' ' if text.endswith((',', ';')) else ', ') + part
    return text


def readme_text(template, decls):
    """README.public.md with every add-on's phrase appended to its tab's line between the addon-tabs markers."""
    if TABS_START not in template and TABS_END not in template:
        return template
    if template.count(TABS_START) != 1 or template.count(TABS_END) != 1:
        raise Declaration(f'README.public.md needs one {TABS_START} and one {TABS_END}')
    head, rest = template.split(TABS_START, 1)
    block, tail = rest.split(TABS_END, 1)
    lines, tabs = block.split('\n'), set()
    for line in lines:
        match = TAB_LINE.match(line)
        if match:
            tabs.add(match[1])
    unknown = [f'{d[2]}: no tab line **{tab}** in README.public.md' for d in decls for tab, _ in d[3] if tab not in tabs]
    if unknown:
        raise Declaration('\n'.join(unknown))
    out = []
    for line in lines:
        match = TAB_LINE.match(line)
        if not match:
            out.append(line)
            continue
        core = match[2].strip().rstrip('.')
        parts = ([core] if core else []) + [text.rstrip('.') for d in decls for tab, text in d[3] if tab == match[1]]
        if parts:
            out.append(f'  - **{match[1]}**: {joined(parts)}.')
    return head + TABS_START + '\n'.join(out) + TABS_END + tail


def write_registry(root, decls):
    if (pathlib.Path(root) / ROOT_DIR).is_dir():
        (pathlib.Path(root) / REGISTRY).write_text(registry_text(decls))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('command', choices=('registry', 'generate', 'next'))
    parser.add_argument('--root', default=str(pathlib.Path(__file__).resolve().parent.parent))
    args = parser.parse_args()
    root = pathlib.Path(args.root)
    try:
        decls = declarations(root)
        if args.command == 'next':
            print(max((d[0] for d in decls), default=0) + 10)
            return 0
        template = root / 'notchcast/README.public.md'
        readme = readme_text(template.read_text(), decls) if template.exists() else None
        write_registry(root, decls)
        if args.command == 'generate' and readme is not None:
            (root / 'README.md').write_text(readme)
    except Declaration as error:
        print(f'add-on declarations: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
